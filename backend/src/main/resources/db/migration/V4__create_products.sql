CREATE TABLE brands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL
);

CREATE UNIQUE INDEX uq_brands_name ON brands (lower(name));

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    summary VARCHAR(255) NOT NULL,
    description TEXT,
    category_id BIGINT NOT NULL REFERENCES categories (id),
    brand_id BIGINT NOT NULL REFERENCES brands (id),
    color VARCHAR(50) CHECK (color = upper(left(color, 1)) || lower(substring(color FROM 2))),
    price NUMERIC(12, 2) NOT NULL CHECK (price > 0),
    old_price NUMERIC(12, 2) CHECK (old_price > price),
    stock INTEGER NOT NULL CHECK (stock >= 0),
    image_url VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_products_category_id ON products (category_id);

CREATE INDEX idx_products_brand_id ON products (brand_id);

CREATE TABLE product_specs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    value VARCHAR(255) NOT NULL,
    position INTEGER NOT NULL,
    UNIQUE (product_id, name) DEFERRABLE INITIALLY DEFERRED,
    UNIQUE (product_id, position) DEFERRABLE INITIALLY DEFERRED
);
